"""SYNTHETIC metered data, so the calibration feature can be demonstrated without real site data.

Every file produced here is labelled SYNTHETIC. The generator knows the "true" load-factor scales,
which makes it useful for checking that calibration recovers them. That proves the mechanics only:
a model that works on data it generated itself says nothing about real-world accuracy.

Readings are half-hourly. Weekday daytime runs near the week's level, evenings and weekends much lower,
a single slot per week reaches the level exactly, readings carry bounded multiplicative noise
(clipped to +/-2 sigma, so weekly maxima are not inflated by freak draws), and occasional outages read 0.
"""

from __future__ import annotations

import sys
from collections.abc import Mapping, Sequence
from datetime import date, datetime, time, timedelta
from pathlib import Path

import numpy as np

from sitepower.calibrate import apply_scales
from sitepower.estimate import estimate
from sitepower.models import Equipment, Project

SLOTS_PER_DAY = 48


def generate_metered(
    project: Project,
    library: Mapping[str, Equipment],
    true_scales: Mapping[str, float],
    start: date,
    seed: int,
    metered_weeks: int | None = None,
    noise: float = 0.02,
    outage_prob: float = 0.005,
) -> list[tuple[datetime, float]]:
    weeks = project.weeks if metered_weeks is None else metered_weeks
    if not 1 <= weeks <= project.weeks:
        raise ValueError(f"metered_weeks must be between 1 and {project.weeks}")
    if noise < 0:
        raise ValueError("noise must not be negative")
    if not 0 <= outage_prob < 1:
        raise ValueError("outage_prob must be at least 0 and below 1")
    truth = estimate(project, apply_scales(library, true_scales)).kw
    base = project.base_load_kw
    rng = np.random.Generator(np.random.PCG64(seed))
    origin = datetime.combine(start, time(0))
    out: list[tuple[datetime, float]] = []
    for w in range(weeks):
        level = float(truth[w])
        slots = [
            origin + timedelta(minutes=30 * (w * 7 * SLOTS_PER_DAY + i))
            for i in range(7 * SLOTS_PER_DAY)
        ]
        daytime = [i for i, t in enumerate(slots) if t.weekday() < 5 and 7 <= t.hour < 17]
        peak_slot = int(rng.choice(daytime))
        for i, t in enumerate(slots):
            hour = t.hour + t.minute / 60
            if t.weekday() < 5 and 7 <= hour < 17:
                u = 0.75 + 0.25 * float(rng.random())
            elif t.weekday() < 5 and 17 <= hour < 22:
                u = 0.4 + 0.2 * float(rng.random())
            else:
                u = 0.15 + 0.15 * float(rng.random())
            z = float(np.clip(rng.standard_normal(), -2.0, 2.0))
            if i == peak_slot:
                kw = level
            elif float(rng.random()) < outage_prob:
                kw = 0.0
            else:
                kw = max(0.0, (base + (level - base) * u) * (1 + noise * z))
            out.append((t, round(kw, 3)))
    return out


def metered_to_csv(
    samples: Sequence[tuple[datetime, float]], note: str = "generated by sitepower.synth"
) -> str:
    lines = [
        "# SYNTHETIC DATA. Not from any real site or meter. For demonstrating the calibration mechanics only.",
        f"# {note}",
        "timestamp,kw",
    ]
    lines += [f"{t:%Y-%m-%d %H:%M},{kw:.3f}" for t, kw in samples]
    return "\n".join(lines) + "\n"


# The scales the bundled sample file was generated with, published so anyone can check recovery.
# ASSUMPTION CHOSEN FOR THE DEMO: the illustrative library under-estimates by roughly 25 % (with some
# variation by category). That is a made-up scenario to show the mechanics, not a finding about real sites.
SAMPLE_TRUE_SCALES: dict[str, float] = {
    "lifting": 1.20, "tools": 1.30, "drying": 1.20, "lighting": 1.25,
    "welfare": 1.30, "plant": 1.20, "commissioning": 1.25,
}  # fmt: skip


def main(out_path: str) -> None:
    from sitepower.io import project_from_json
    from sitepower.library import parse_equipment_csv

    data = Path(__file__).resolve().parents[2] / "data"
    library = parse_equipment_csv(
        (data / "equipment.illustrative.csv").read_text(encoding="utf-8")
    ).library
    project = project_from_json((data / "sample_project.json").read_text(encoding="utf-8"))
    samples = generate_metered(
        project, library, SAMPLE_TRUE_SCALES, date(2025, 1, 6), seed=2025, metered_weeks=16
    )
    truth = ", ".join(f"{k}={v}" for k, v in SAMPLE_TRUE_SCALES.items())
    note = f"project start 2025-01-06, first 16 weeks, seed 2025; true load-factor scales used: {truth}"
    Path(out_path).write_text(metered_to_csv(samples, note), encoding="utf-8")
    print(f"wrote {len(samples)} half-hourly readings to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/sample_metered.synthetic.csv")
